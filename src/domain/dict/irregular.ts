/** 三段合并为单一查询表；跨段同 key 值不一致视为表数据损坏，抛错早死。 */
function buildIrregularMap(): Record<string, string> {
  const merged: Record<string, string> = {}
  for (const segment of [PAST_TENSE_MAP, PAST_PARTICIPLE_MAP, PLURAL_MAP] as const) {
    for (const [form, lemma] of Object.entries(segment)) {
      const existing = merged[form]
      if (existing !== undefined && existing !== lemma) {
        throw new Error(`irregular.ts 表冲突：${form} 已映射到 ${existing}，又映射到 ${lemma}`)
      }
      merged[form] = lemma
    }
  }
  return merged
}

export const IRREGULAR_MAP: Record<string, string> = buildIrregularMap()
